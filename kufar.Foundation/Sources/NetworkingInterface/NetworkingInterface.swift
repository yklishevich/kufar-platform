import Foundation

// Абстрактная поверхность сетевой границы. Реализация — в `Networking`,
// и ни один потребитель этого таргета её не видит.
//
// Правило из 2.2 («протокол принадлежит тому, кто его использует, и лежит
// на уровне самого нижнего потребителя») выполняется для обоих протоколов
// одинаково, и определяет оно ПАКЕТ: `kufar.Foundation`, ниже спускаться
// некуда, от него зависят все. Деление на таргеты внутри пакета отвечает
// на другой вопрос — абстракция против реализации.
//
// Инверсия при этом только у одного, и путать эти два случая легко:
//
//   • `RequestInterceptor` — потребитель `APIClient` на дне, реализующий
//     `Auth` наверху. Вызов идёт против зависимости сборки. Инверсия.
//   • `HTTPPerforming` — потребители `*Data` наверху, реализующий
//     `APIClient` на дне. Вызов и зависимость сонаправлены. Не инверсия,
//     а подменяемость: адаптер становится тестируемым без сети.

/// Транспорт, каким его видит адаптер вертикали.
///
/// Практическое следствие — адаптер становится тестируемым: подменяется
/// не сеть, а сам транспорт (`NetworkingTesting`). До этого проверить
/// разбор ответа внутри `Remote*Repository` было нечем.
public protocol HTTPPerforming: Sendable {
    func get(_ path: String) async throws -> Data
}

/// Точка расширения: потребитель здесь `APIClient`, а реализуют её наверху.
///
/// Инверсия зависимостей в чистом виде — зависимость сборки идёт
/// Auth → Foundation (вниз), вызов в рантайме снизу вверх. Положи протокол
/// в `Auth` — и сети пришлось бы импортировать аутентификацию: цикл.
///
/// Практическая причина именно для классифайда: лента гостю, поиск и просмотр
/// объявления работают до логина. Сеть, умеющая только авторизованные запросы,
/// не переиспользуется для большей части трафика.
///
/// Лежит рядом с `HTTPPerforming`, а не в `Networking`, по той же причине,
/// по которой `SessionInterface` лежит отдельно от `Auth`: реализующему
/// нужен контракт, а не `APIClient` вместе с ним.
public protocol RequestInterceptor: Sendable {
    func adapt(_ request: URLRequest) async throws -> URLRequest
    func retry(_ request: URLRequest, dueTo error: any Error) async -> RetryDecision
}

public enum RetryDecision: Sendable {
    case retry
    case giveUp
}
