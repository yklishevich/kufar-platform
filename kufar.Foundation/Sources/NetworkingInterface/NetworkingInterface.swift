import Foundation

/// Абстракция транспорта для адаптеров.
///
/// Владение здесь противоположно `RequestInterceptor`, хотя граница одна:
///
///   • `RequestInterceptor` потребляет `APIClient` — протокол принадлежит
///     поставщику услуги и живёт в `Networking`;
///   • `HTTPPerforming` потребляют шесть `*Data` — протокол принадлежит
///     им, а лежит на уровне самого нижнего общего потребителя. Ниже
///     `kufar.Foundation` спускаться некуда: от него зависят все.
///
/// Зачем отдельный таргет, а не объявление внутри `Networking`: иначе
/// репозиторий ради контракта импортирует реализацию. Тот же довод, по
/// которому `SessionInterface` лежит отдельно от `Auth`.
///
/// Практическое следствие — адаптер становится тестируемым: подменяется
/// не сеть, а сам транспорт (`NetworkingTesting`). До этого проверить
/// разбор ответа внутри `Remote*Repository` было нечем.
public protocol HTTPPerforming: Sendable {
    func get(_ path: String) async throws -> Data
}
